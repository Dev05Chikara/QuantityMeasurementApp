namespace QuantityMeasurementApp
{
    /// <summary>
    /// Enumeration representing the units of length measurement (Feet and Inch).
    /// </summary>
    /// <param name="FEET">Represents the unit of measurement in feet.</param>
    /// <param name="INCH">Represents the unit of measurement in inches.</param>
    
    
    // This enum defines the supported length units for the Length class, allowing for clear and type-safe representation of measurement units in the quantity measurement application.
    public enum LengthUnit
    {
        FEET,
        INCH
    }
}